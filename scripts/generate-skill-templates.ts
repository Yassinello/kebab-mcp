#!/usr/bin/env tsx
/**
 * generate-skill-templates — Kebab House phase 0 (RIT-02).
 *
 * The ritual templates live as plain Agent Skills folders in
 * `content/skill-templates/<name>/SKILL.md` (easy to read, diff and
 * contribute). Serverless bundles (Vercel) do not reliably ship arbitrary
 * repo files, so this script inlines them into a TS module that the
 * bundler always includes:
 *
 *   src/connectors/skills/lib/templates.generated.ts
 *
 * Usage:
 *   npm run gen:skill-templates            # rewrite the module
 *   npm run gen:skill-templates -- --check # exit 1 if it is stale
 *
 * `src/connectors/skills/templates.test.ts` also fails when the module
 * drifts from the files, so a forgotten regeneration is caught in CI.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { format, resolveConfig } from "prettier";

const ROOT = resolve(__dirname, "..");
const TEMPLATES_DIR = join(ROOT, "content", "skill-templates");
const OUT = join(ROOT, "src", "connectors", "skills", "lib", "templates.generated.ts");

function readTemplates(): { folder: string; skillMd: string }[] {
  return readdirSync(TEMPLATES_DIR)
    .filter((d) => statSync(join(TEMPLATES_DIR, d)).isDirectory())
    .sort()
    .map((folder) => ({
      folder,
      skillMd: readFileSync(join(TEMPLATES_DIR, folder, "SKILL.md"), "utf-8"),
    }));
}

async function render(): Promise<string> {
  const entries = readTemplates()
    .map((t) => `  { folder: ${JSON.stringify(t.folder)}, skillMd: ${JSON.stringify(t.skillMd)} },`)
    .join("\n");
  const src = `/**
 * GENERATED by scripts/generate-skill-templates.ts from
 * content/skill-templates/<name>/SKILL.md. Do not edit by hand:
 * edit the SKILL.md files, then run \`npm run gen:skill-templates\`.
 */

export const SKILL_TEMPLATE_SOURCES: ReadonlyArray<{ folder: string; skillMd: string }> = [
${entries}
];
`;
  const config = (await resolveConfig(OUT)) ?? {};
  return format(src, { ...config, filepath: OUT });
}

async function main() {
  const next = await render();
  const check = process.argv.includes("--check");
  let current: string;
  try {
    current = readFileSync(OUT, "utf-8");
  } catch {
    current = ""; // first run: the module does not exist yet
  }
  if (check) {
    if (current !== next) {
      console.error(`${OUT} is stale. Run: npm run gen:skill-templates`);
      process.exit(1);
    }
    console.log("skill templates module is up to date");
    return;
  }
  if (current === next) {
    console.log("skill templates module already up to date");
    return;
  }
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT}`);
}

void main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
